#!/usr/bin/env python3
"""TIMELINE.md for the 2026-09-14 campaign C (sc2 + AMD rules), in Israel time, main events only.
Reads the four chain driver logs (fetched as driver_<node>.log in this dir) and the header lines kept in
TIMELINE.header.md (launch/fetch/release notes typed by hand). Regenerates TIMELINE.md fully each time."""
import glob, os, re
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
IL = timezone(timedelta(hours=3))  # Asia/Jerusalem, DST in September
NODE = {"amd-mi355x-2": "node 2 (all chains, sequential)",
        }
LINE = re.compile(r"^=== (\w+) (\w+) (detect|pass1|pass2)(?: arm=(\w+) start| )?\s*(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ)")
DONE = re.compile(r"^ALL_DONE (\w+) (\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ)")


def il(ts):
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc).astimezone(IL).strftime("%Y-%m-%d %H:%M")


def main():
    events = []
    for f in sorted(glob.glob(os.path.join(HERE, "driver_*.log"))):
        node = os.path.basename(f)[7:-4]
        for line in open(f, errors="ignore"):
            m = LINE.match(line)
            if m:
                tag, mode, phase, arm, ts = m.groups()
                what = f"{tag} {mode} {phase}" + (f" arm {arm} server start" if arm else " start")
                events.append((ts, f"{NODE.get(node, node)}: {what}"))
                continue
            m = DONE.match(line)
            if m:
                events.append((m.group(2), f"{NODE.get(node, node)}: ALL DONE ({m.group(1)})"))
    hdr = open(os.path.join(HERE, "TIMELINE.header.md")).read() if os.path.exists(os.path.join(HERE, "TIMELINE.header.md")) else ""
    out = ["# TIMELINE — in-model campaign 2026-09-10 (Israel time, UTC+3). Main events only; regenerated by make_timeline.py from the driver logs.\n", hdr]
    for ts, what in sorted(events):
        out.append(f"- {il(ts)}  {what}")
    open(os.path.join(HERE, "TIMELINE.md"), "w").write("\n".join(out) + "\n")
    print(f"{len(events)} events")


if __name__ == "__main__":
    main()
